create table usuario (
    id          bigint generated by default as identity primary key,
    perfil      varchar(31)  not null,
    nome        varchar(120) not null,
    email       varchar(160) not null unique,
    senha_hash  varchar(100) not null,
    ativo       boolean      not null default true
);

create table empresa (
    id     bigint generated by default as identity primary key,
    nome   varchar(160) not null,
    cnpj   varchar(14)  not null unique,
    setor  varchar(80)  not null
);

create table planta (
    id               bigint generated by default as identity primary key,
    empresa_id       bigint       not null references empresa (id),
    nome             varchar(160) not null,
    localizacao      varchar(200) not null,
    tipo             varchar(20)  not null,
    status           varchar(20)  not null,
    documentacao_ok  boolean      not null default false,
    inativada_em     timestamp
);

create table fonte_emissao (
    id         bigint generated by default as identity primary key,
    planta_id  bigint       not null references planta (id),
    tipo       varchar(40)  not null,
    descricao  varchar(200) not null
);

create table fator_emissao (
    id               bigint generated by default as identity primary key,
    tipo_fonte       varchar(40)    not null,
    valor            numeric(12, 6) not null,
    unidade          varchar(30)    not null,
    vigencia_inicio  date           not null,
    vigencia_fim     date
);

create table consumo (
    id           bigint generated by default as identity primary key,
    fonte_id     bigint         not null references fonte_emissao (id),
    quantidade   numeric(18, 3) not null,
    competencia  date           not null
);

create table calculo (
    id              bigint generated by default as identity primary key,
    empresa_id      bigint         not null references empresa (id),
    cenario         varchar(120)   not null,
    periodo_inicio  date           not null,
    periodo_fim     date           not null,
    escopo1         numeric(18, 3) not null,
    escopo2         numeric(18, 3) not null,
    escopo3         numeric(18, 3) not null,
    total_co2e      numeric(18, 3) not null,
    origem_fatores  varchar(20)    not null,
    data_calculo    timestamp      not null
);

create table compensacao (
    id                    bigint generated by default as identity primary key,
    calculo_id            bigint         not null references calculo (id),
    tipo_acao             varchar(40)    not null,
    descricao             varchar(300)   not null,
    creditos_necessarios  numeric(18, 3) not null,
    quantidade            numeric(18, 3) not null,
    unidade               varchar(30)    not null,
    custo_estimado        numeric(18, 2) not null
);

create table relatorio (
    id               bigint generated by default as identity primary key,
    empresa_id       bigint       not null references empresa (id),
    calculo_id       bigint       not null references calculo (id),
    tipo             varchar(30)  not null,
    formato          varchar(10)  not null,
    gerado_em        timestamp    not null,
    chave_storage    varchar(200) not null,
    protocolo_envio  varchar(40),
    enviado_em       timestamp
);

create index idx_planta_empresa on planta (empresa_id);
create index idx_fonte_planta on fonte_emissao (planta_id);
create index idx_consumo_fonte_competencia on consumo (fonte_id, competencia);
create index idx_calculo_empresa on calculo (empresa_id);
create index idx_compensacao_calculo on compensacao (calculo_id);
create index idx_relatorio_empresa on relatorio (empresa_id);
